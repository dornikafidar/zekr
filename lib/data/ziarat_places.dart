/// Sacred places + associated ziyarat.
class ZiaratAudioSource {
  const ZiaratAudioSource({
    required this.id,
    required this.labelFa,
    required this.url,
  });

  /// Stable id for sync packs under assets/audio/ziarat/sync/{ziaratId}/.
  final String id;
  final String labelFa;
  final String url;
}

class ZiaratItem {
  const ZiaratItem({
    required this.id,
    required this.titleFa,
    required this.arabicPreview,
    this.streamUrl,
    this.streamLabel,
    this.audioSources = const [],
  });

  final String id;
  final String titleFa;
  final String arabicPreview;

  /// Preferred human recitation (stream). Used instead of TTS "vorlesen".
  final String? streamUrl;
  final String? streamLabel;

  /// Multiple human recitations (e.g. Ashura from erfan.ir).
  final List<ZiaratAudioSource> audioSources;

  bool get hasSyncedAudio => true;

  List<ZiaratAudioSource> get resolvedAudioSources {
    if (audioSources.isNotEmpty) return audioSources;
    if (streamUrl != null && streamUrl!.isNotEmpty) {
      return [
        ZiaratAudioSource(
          id: id,
          labelFa: streamLabel ?? titleFa,
          url: streamUrl!,
        ),
      ];
    }
    return const [];
  }
}

